INSERT INTO countries (id, code, name, currency, status, is_international_fallback, active, configured, fallback, created_at, updated_at)
SELECT (SUBSTRING(md5('country:' || s.code), 1, 8) || '-' ||
        SUBSTRING(md5('country:' || s.code), 9, 4) || '-' ||
        SUBSTRING(md5('country:' || s.code), 13, 4) || '-' ||
        SUBSTRING(md5('country:' || s.code), 17, 4) || '-' ||
        SUBSTRING(md5('country:' || s.code), 21, 12))::UUID,
       s.code,
       s.name,
       s.currency,
       'ACTIVE',
       FALSE,
       TRUE,
       FALSE,
       FALSE,
       NOW(),
       NOW()
FROM seed s
ON CONFLICT (code) DO UPDATE
SET name = EXCLUDED.name,
    currency = EXCLUDED.currency,
    active = TRUE,
    status = 'ACTIVE',
    fallback = FALSE,
    is_international_fallback = FALSE,
    updated_at = NOW();

