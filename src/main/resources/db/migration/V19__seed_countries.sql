    fallback = TRUE,
    status = 'ACTIVE',
    is_international_fallback = TRUE,
    updated_at = NOW();

UPDATE countries
SET fallback = FALSE,
    is_international_fallback = FALSE
WHERE code <> 'INT'
  AND fallback = TRUE;

UPDATE countries
SET configured = TRUE
WHERE code IN (
    SELECT UPPER(ac.country_code)
    FROM admin_countries ac
    WHERE ac.active = TRUE
    UNION
    SELECT UPPER(sp.country)
    FROM subscription_plans sp
    WHERE sp.active = TRUE
)
AND code <> 'INT';

UPDATE countries
SET status = CASE WHEN active THEN 'ACTIVE' ELSE 'INACTIVE' END,
    is_international_fallback = fallback;
