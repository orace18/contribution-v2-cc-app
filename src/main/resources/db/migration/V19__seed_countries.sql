ALTER TABLE countries
    ADD COLUMN IF NOT EXISTS active BOOLEAN,
    ADD COLUMN IF NOT EXISTS configured BOOLEAN,
    ADD COLUMN IF NOT EXISTS fallback BOOLEAN;

UPDATE countries
SET active = CASE
    WHEN status = 'ACTIVE' THEN TRUE
    ELSE FALSE
END
WHERE active IS NULL;

UPDATE countries
SET configured = COALESCE(configured, active, FALSE)
WHERE configured IS NULL;

UPDATE countries
SET fallback = COALESCE(fallback, is_international_fallback, FALSE)
WHERE fallback IS NULL;

ALTER TABLE countries
    ALTER COLUMN active SET NOT NULL,
    ALTER COLUMN configured SET NOT NULL,
    ALTER COLUMN fallback SET NOT NULL,
    ALTER COLUMN active SET DEFAULT TRUE,
    ALTER COLUMN configured SET DEFAULT FALSE,
    ALTER COLUMN fallback SET DEFAULT FALSE;

ALTER TABLE countries
    ALTER COLUMN status SET DEFAULT 'ACTIVE',
    ALTER COLUMN is_international_fallback SET DEFAULT FALSE;

